
import { NextRequest, NextResponse } from "next/server";
import { supabaseAdmin } from "@/lib/supabase";

export async function POST(req: NextRequest) {
    try {
        const body = await req.json();
        const { meetingId } = body;

        if (!meetingId) {
            return NextResponse.json({ error: "Missing meetingId" }, { status: 400 });
        }

        // Simulate AI Processing Delay
        await new Promise(resolve => setTimeout(resolve, 2000));

        // Fetch real meeting details for context
        const { data: meeting } = await supabaseAdmin
            .from('meetings')
            .select('name, created_at')
            .eq('id', meetingId)
            .single();

        const { data: participants } = await supabaseAdmin
            .from('meeting_participants')
            .select('name, role')
            .eq('meeting_id', meetingId);

        const studentName = participants?.find(p => p.role === 'student' || p.role === 'learner')?.name || "Student";
        const dateStr = meeting?.created_at ? new Date(meeting.created_at).toLocaleDateString('en-US', { day: 'numeric', month: 'long', year: 'numeric' }) : new Date().toLocaleDateString();
        const topic = meeting?.name || "General Session";

        // Sample "Insightful" Summary Data using the new template
        const sampleSummary = `
            <div style="font-family: sans-serif; color: #333; line-height: 1.6;">
                <h2 style="color: #4f46e5; border-bottom: 2px solid #e0e7ff; padding-bottom: 0.5rem; margin-top: 0;">
                    🚀 Session Insight Report: ${topic}
                </h2>
                <p style="color: #64748b; font-size: 0.9em; margin-bottom: 2rem;">
                    <strong>Student:</strong> ${studentName} &nbsp;|&nbsp; <strong>Date:</strong> ${dateStr}
                </p>

                <h3 style="color: #1e293b; margin-top: 1.5rem;">📊 Engagement Analytics (Focus Orbit™)</h3>
                <div style="background: #f8fafc; border-left: 4px solid #4f46e5; padding: 1rem; margin-bottom: 1.5rem; border-radius: 0 8px 8px 0;">
                    <p style="margin: 0 0 0.5rem 0;"><strong>1. Focus Performance</strong></p>
                    <ul style="list-style: none; padding: 0; margin: 0;">
                        <li><strong>Overall Focus Score:</strong> 88%</li>
                        <li><strong>Focus Intensity:</strong> 🟢 High (The student remained consistently engaged for the duration of the lesson).</li>
                        <li><strong>Distraction Log:</strong> 2 brief moments of window-switching detected.</li>
                    </ul>

                    <p style="margin: 1rem 0 0.5rem 0;"><strong>2. Participation & Voice</strong></p>
                    <ul style="list-style: none; padding: 0; margin: 0;">
                        <li><strong>Student Talk Time:</strong> 🗣️ 45%</li>
                        <li><strong>Tutor Talk Time:</strong> 👨‍🏫 55%</li>
                        <li><strong>Insight:</strong> The student led the conversation during the problem-solving phase, showing high confidence.</li>
                    </ul>
                </div>

                <h3 style="color: #1e293b;">💡 Key Breakthroughs & Wins</h3>
                <ul style="margin-bottom: 1.5rem;">
                    <li><strong>Moment of Clarity:</strong> Identified the relationship between the coefficients and the parabola's vertex correctly without assistance.</li>
                    <li><strong>Skill Mastery:</strong> Successfully applied the quadratic formula to solve real-world word problems.</li>
                </ul>

                <h3 style="color: #1e293b;">📝 Academic Summary</h3>
                <p style="margin-bottom: 1.5rem;">
                    In this session, we covered <strong>Quadratic Equations and Functions</strong>. We reviewed factorization techniques and moved on to graphing parabolas. ${studentName} showed great improvement in identifying the axis of symmetry and vertex coordinates.
                </p>

                <h3 style="color: #1e293b;">🏠 Homework & Next Steps</h3>
                <div style="background: #fff1f2; border: 1px solid #fecdd3; padding: 1rem; border-radius: 8px;">
                    <ul style="margin: 0; padding-left: 1.2rem;">
                        <li><strong>Task:</strong> Complete the 5 practice problems on "Completing the Square" (Worksheet 4B).</li>
                        <li><strong>Focus Goal for Next Session:</strong> Aim for 90% focus score by minimizing browser tab switching.</li>
                    </ul>
                </div>

                <p style="text-align: center; color: #94a3b8; font-size: 0.8em; margin-top: 3rem; border-top: 1px solid #e2e8f0; padding-top: 1rem;">
                    Generated by SessionOrbit.com — 24/7 AI Tech Support Enabled.
                </p>
            </div>
        `;

        // Check if summary exists
        const { data: existing } = await supabaseAdmin
            .from('meeting_summaries')
            .select('id')
            .eq('meeting_id', meetingId)
            .maybeSingle();

        let error;

        if (existing) {
            const { error: updateError } = await supabaseAdmin
                .from('meeting_summaries')
                .update({ summary: sampleSummary })
                .eq('meeting_id', meetingId);
            error = updateError;
        } else {
            const { error: insertError } = await supabaseAdmin
                .from('meeting_summaries')
                .insert({
                    meeting_id: meetingId,
                    summary: sampleSummary
                });
            error = insertError;
        }

        if (error) {
            throw error;
        }

        return NextResponse.json({ success: true, summary: sampleSummary });

    } catch (error: any) {
        console.error("Generate Summary Error:", error);
        return NextResponse.json({ error: error.message }, { status: 500 });
    }
}
