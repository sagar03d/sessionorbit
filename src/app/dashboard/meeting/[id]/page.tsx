"use client"

import { useEffect, useState, use } from "react"
import { supabase } from "@/lib/supabase"
import { useRouter } from "next/navigation"
import { ArrowLeft, Clock, Users, FileText, Calendar, Download, Play, ShieldAlert, BrainCircuit, Zap, Loader2, Mail } from "lucide-react"
import { Button } from "@/components/ui/button"
import dynamic from "next/dynamic"

const PDFPreview = ({ meeting, participants, summary }: any) => {
    const [url, setUrl] = useState<string | null>(null);

    useEffect(() => {
        const generatePdf = async () => {
            try {
                const { pdf } = await import('@react-pdf/renderer');
                const SessionReportPDF = (await import('@/components/reports/SessionReportPDF')).default;
                const blob = await pdf(<SessionReportPDF meeting={meeting} participants={participants} summary={summary} />).toBlob();
                const blobUrl = URL.createObjectURL(blob);
                setUrl(blobUrl);
            } catch (error) {
                console.error("PDF Preview generation failed", error);
            }
        };
        generatePdf();

        return () => {
            if (url) URL.revokeObjectURL(url);
        };
    }, []); // Run once on mount

    if (!url) {
        return <div className="h-full w-full flex items-center justify-center bg-neutral-900 text-neutral-500">
            <Loader2 className="w-8 h-8 animate-spin" />
        </div>;
    }

    return (
        <iframe
            src={url}
            className="w-full h-full border-none"
            title="PDF Preview"
        />
    );
};

const SessionReportPDF = dynamic(
    () => import("@/components/reports/SessionReportPDF"),
    { ssr: false }
);

export default function MeetingDetailsPage({ params }: { params: Promise<{ id: string }> }) {
    const { id } = use(params)
    const router = useRouter()
    const [meeting, setMeeting] = useState<any>(null)
    const [participants, setParticipants] = useState<any[]>([])
    const [transcriptions, setTranscriptions] = useState<any[]>([])
    const [summary, setSummary] = useState<any>(null)
    const [isLoading, setIsLoading] = useState(true)
    const [isGenerating, setIsGenerating] = useState(false)

    const handleGenerateSummary = async () => {
        setIsGenerating(true)
        try {
            const res = await fetch('/api/meeting/generate-summary', {
                method: 'POST',
                headers: { 'Content-Type': 'application/json' },
                body: JSON.stringify({ meetingId: id })
            })
            const data = await res.json()
            if (data.success && data.summary) {
                setSummary({ summary: data.summary })
            }
        } catch (error) {
            console.error("Failed to generate summary", error)
        } finally {
            setIsGenerating(false)
        }
    }

    const [isSending, setIsSending] = useState(false)

    const handleSendEmail = async () => {
        const email = window.prompt("Enter parent's email address:")
        if (!email) return

        setIsSending(true)
        try {
            const res = await fetch('/api/meeting/send-report', {
                method: 'POST',
                headers: { 'Content-Type': 'application/json' },
                body: JSON.stringify({ meetingId: id, email })
            })
            const data = await res.json()
            if (data.success) {
                alert(data.mocked ? "Email sending simulated (API Key missing)." : "Report sent successfully!")
            } else {
                alert("Failed to send report: " + (data.error || "Unknown error"))
            }
        } catch (error) {
            console.error("Email send failed", error)
            alert("Failed to send email.")
        } finally {
            setIsSending(false)
        }
    }

    const handleDownloadPDF = () => {
        const summaryContent = summary?.summary || "";

        // Sanitize content minimally (basic escape) or trust it if generated by AI backend.
        // Even better: Use a Blob URL to avoid document.write which triggers security warnings.

        const htmlContent = `
            <!DOCTYPE html>
            <html>
            <head>
                <title>SessionOrbit Report - ${meeting?.name || 'Session'}</title>
                <style>
                    body { font-family: system-ui, -apple-system, sans-serif; padding: 20px; max-width: 800px; margin: 0 auto; color: #1a1a1a; white-space: pre-wrap; }
                    h2 { color: #4f46e5; border-bottom: 2px solid #e0e7ff; padding-bottom: 0.5rem; }
                    .print-footer { margin-top: 30px; font-size: 12px; color: #666; text-align: center; border-top: 1px solid #eee; padding-top: 10px; }
                    /* Ensure colors print correctly */
                    * { -webkit-print-color-adjust: exact; print-color-adjust: exact; }
                </style>
            </head>
            <body>
                <div id="content"></div>
                <script>
                    // Safe injection using innerText to prevent XSS
                    const content = ${JSON.stringify(summaryContent)};
                    document.getElementById('content').innerText = content;
                    
                    window.onload = function() {
                        setTimeout(() => {
                            window.print();
                        }, 500);
                    }
                </script>
            </body>
            </html>
        `;

        const blob = new Blob([htmlContent], { type: 'text/html' });
        const url = URL.createObjectURL(blob);

        const printWindow = window.open(url, '_blank');
        if (!printWindow) {
            alert("Please allow popups to download the report.");
            return;
        }

        // Cleanup
        // We can't revoke immediately because the new window needs to load it.
        // Rely on browser cleanup or a timeout.
        setTimeout(() => URL.revokeObjectURL(url), 60000); // 1 minute
    }

    useEffect(() => {
        const fetchData = async () => {
            try {
                const { data: { session } } = await supabase.auth.getSession();
                const headers: HeadersInit = {};
                if (session?.access_token) {
                    headers['Authorization'] = `Bearer ${session.access_token}`;
                }

                const res = await fetch(`/api/meetings/${id}`, { headers })
                if (!res.ok) {
                    const errorData = await res.json().catch(() => ({}))
                    console.error("Fetch error:", res.status, errorData)

                    if (res.status === 404) {
                        setMeeting(null) // truly not found
                    } else if (res.status === 401) {
                        router.push('/login?next=/dashboard/meeting/' + id)
                        return
                    } else if (res.status === 403) {
                        alert("You do not have permission to view this meeting.")
                        router.push('/dashboard')
                        return
                    } else {
                        throw new Error(errorData.error || "Failed to fetch meeting data")
                    }
                    return
                }

                const data = await res.json()

                setMeeting(data.meeting)
                setParticipants(data.participants)
                setTranscriptions(data.transcriptions)
                setSummary(data.summary)
            } catch (error: any) {
                console.error("Error fetching meeting data:", error)
            } finally {
                setIsLoading(false)
            }
        }

        fetchData()
    }, [id])

    if (isLoading) {
        return (
            <div className="min-h-screen bg-black text-white flex items-center justify-center p-8">
                <div className="animate-spin rounded-full h-8 w-8 border-b-2 border-white"></div>
            </div>
        )
    }

    if (!meeting) {
        return (
            <div className="min-h-screen bg-black text-white flex items-center justify-center p-8">
                <p>Meeting not found.</p>
            </div>
        )
    }

    // Calculate generic stats
    const totalDurationSeconds = meeting.ended_at
        ? (new Date(meeting.ended_at).getTime() - new Date(meeting.created_at).getTime()) / 1000
        : 0

    // Format helpers
    const formatDuration = (seconds: number) => {
        const h = Math.floor(seconds / 3600)
        const m = Math.floor((seconds % 3600) / 60)
        const s = Math.floor(seconds % 60)
        return `${h > 0 ? h + 'h ' : ''}${m}m ${s}s`
    }

    return (
        <div className="min-h-screen bg-black text-white p-8 lg:p-12">
            <div className="max-w-5xl mx-auto space-y-8">
                {/* Header */}
                <div>
                    <Button
                        variant="ghost"
                        className="pl-0 text-neutral-400 hover:text-white mb-4"
                        onClick={() => router.back()}
                    >
                        <ArrowLeft className="w-4 h-4 mr-2" /> Back to Dashboard
                    </Button>
                    <div className="flex items-start justify-between">
                        <div className="space-y-1">
                            <h1 className="text-3xl font-bold">{meeting.name}</h1>
                            <div className="flex items-center gap-4 text-neutral-400 text-sm">
                                <div className="flex items-center gap-2">
                                    <Calendar className="w-4 h-4" />
                                    {new Date(meeting.created_at).toLocaleDateString()}
                                </div>
                                <div className="flex items-center gap-2">
                                    <Clock className="w-4 h-4" />
                                    {new Date(meeting.created_at).toLocaleTimeString()}
                                </div>
                            </div>
                        </div>
                        {meeting.ended_at && (
                            <div className="px-3 py-1 rounded-full bg-neutral-900 border border-neutral-800 text-sm text-neutral-400">
                                Duration: {formatDuration(totalDurationSeconds)}
                            </div>
                        )}
                    </div>
                </div>

                {/* Recording Player Section */}
                {meeting.recording_url ? (
                    <div className="rounded-2xl overflow-hidden border border-neutral-800 bg-neutral-900/50 backdrop-blur-sm shadow-2xl group/player">
                        <div className="p-5 border-b border-neutral-800 flex items-center justify-between bg-neutral-900/80">
                            <div className="flex items-center gap-3">
                                <div className="w-8 h-8 rounded-lg bg-blue-500/10 flex items-center justify-center">
                                    <Play className="w-4 h-4 text-blue-500" />
                                </div>
                                <div>
                                    <h2 className="text-sm font-bold text-white tracking-tight">Class Replay</h2>
                                    <p className="text-[10px] text-neutral-500 font-medium uppercase tracking-widest">Recorded Session</p>
                                </div>
                            </div>
                            <div className="flex items-center gap-2">
                                <a
                                    href={meeting.recording_url}
                                    download={`recording-${meeting.id}.mp4`}
                                    className="flex items-center gap-2 px-3 py-1.5 rounded-lg bg-neutral-800 text-xs font-bold text-neutral-300 hover:bg-neutral-700 hover:text-white transition-all border border-neutral-700 shadow-sm"
                                >
                                    <Download className="w-3.5 h-3.5" />
                                    Download
                                </a>
                                <a
                                    href={meeting.recording_url}
                                    target="_blank"
                                    rel="noopener noreferrer"
                                    className="px-3 py-1.5 rounded-lg bg-blue-600 text-xs font-bold text-white hover:bg-blue-500 transition-all shadow-lg shadow-blue-500/20"
                                >
                                    Full View
                                </a>
                            </div>
                        </div>
                        <div className="aspect-video bg-black relative">
                            <video
                                src={meeting.recording_url}
                                controls
                                className="w-full h-full object-contain"
                            />
                        </div>
                    </div>
                ) : meeting.egress_id ? (
                    <div className="rounded-2xl p-12 border border-dashed border-neutral-800 bg-neutral-900/20 flex flex-col items-center justify-center text-center space-y-4">
                        <div className="w-16 h-16 rounded-full bg-red-500/10 flex items-center justify-center animate-pulse">
                            <div className="w-3 h-3 rounded-full bg-red-500" />
                        </div>
                        <div className="space-y-1">
                            <h2 className="text-lg font-bold text-white uppercase tracking-tighter">Live Recording in Progress</h2>
                            <p className="text-neutral-500 text-sm max-w-xs mx-auto">This session is currently being recorded. The replay will be available shortly after the meeting ends.</p>
                        </div>
                    </div>
                ) : meeting.ended_at && !meeting.recording_url && (
                    <div className="rounded-2xl p-12 border border-neutral-800 bg-neutral-900/30 flex flex-col items-center justify-center text-center space-y-4">
                        <div className="w-12 h-12 rounded-full bg-neutral-800 flex items-center justify-center text-neutral-500">
                            <Clock className="w-6 h-6 animate-spin" />
                        </div>
                        <div className="space-y-1">
                            <h2 className="text-sm font-bold text-neutral-300 uppercase tracking-widest">Processing Recording</h2>
                            <p className="text-neutral-500 text-xs">We're finalizing the class video. Please check back in a few minutes.</p>
                        </div>
                    </div>
                )}

                {/* Summary Section */}
                {summary ? (
                    <div className="p-6 rounded-2xl border border-neutral-800 bg-neutral-900/50 backdrop-blur-sm space-y-4">
                        <div className="flex items-center justify-between">
                            <h2 className="text-xl font-semibold flex items-center gap-2">
                                <FileText className="w-5 h-5 text-purple-500" /> AI Class Summary
                            </h2>
                            <div className="flex items-center gap-2">
                                <Button
                                    variant="outline"
                                    size="sm"
                                    className="h-8 text-xs gap-2 bg-transparent border-neutral-700 text-neutral-300 hover:bg-neutral-800 hover:text-white"
                                    onClick={handleSendEmail}
                                    disabled={isSending}
                                >
                                    {isSending ? <Loader2 className="w-3 h-3 animate-spin" /> : <Mail className="w-3 h-3" />}
                                    {isSending ? "Sending..." : "Send to Parent"}
                                </Button>

                                <Button
                                    variant="outline"
                                    size="sm"
                                    className="h-8 text-xs gap-2 bg-transparent border-neutral-700 text-neutral-300 hover:bg-neutral-800 hover:text-white"
                                    onClick={async () => {
                                        try {
                                            const { pdf } = await import('@react-pdf/renderer');
                                            const SessionReportPDF = (await import('@/components/reports/SessionReportPDF')).default;
                                            const blob = await pdf(<SessionReportPDF meeting={meeting} participants={participants} summary={summary} />).toBlob();
                                            const url = URL.createObjectURL(blob);
                                            const link = document.createElement('a');
                                            link.href = url;
                                            link.download = `SessionOrbit-Report-${meeting.name || 'Session'}.pdf`;
                                            document.body.appendChild(link);
                                            link.click();
                                            document.body.removeChild(link);
                                            URL.revokeObjectURL(url);
                                        } catch (err) {
                                            console.error("PDF Generation failed:", err);
                                            alert("Failed to generate PDF. Please try again.");
                                        }
                                    }}
                                >
                                    <Download className="w-3 h-3" /> PDF
                                </Button>
                            </div>
                        </div>

                        <div className="rounded-xl overflow-hidden border border-neutral-800 bg-neutral-900/50 h-[800px]">
                            {/* Iframe Preview - avoids React-PDF component crashes */}
                            <PDFPreview meeting={meeting} participants={participants} summary={summary} />
                        </div>
                    </div>
                ) : (
                    <div className="p-8 rounded-2xl border border-dashed border-neutral-800 bg-neutral-900/20 flex flex-col items-center justify-center text-center space-y-4">
                        <div className="w-12 h-12 rounded-full bg-purple-500/10 flex items-center justify-center">
                            <BrainCircuit className="w-6 h-6 text-purple-500" />
                        </div>
                        <div className="space-y-1">
                            <h2 className="text-lg font-bold text-white">Generate Parent Report</h2>
                            <p className="text-neutral-400 text-sm max-w-md mx-auto">Create an insightful, AI-powered summary of this session to share with parents.</p>
                        </div>
                        <Button
                            onClick={handleGenerateSummary}
                            disabled={isGenerating}
                            className="bg-purple-600 hover:bg-purple-700 text-white"
                        >
                            {isGenerating ? (
                                <>
                                    <Loader2 className="w-4 h-4 mr-2 animate-spin" /> Generating...
                                </>
                            ) : (
                                <>
                                    <Zap className="w-4 h-4 mr-2" /> Generate Summary
                                </>
                            )}
                        </Button>
                    </div>
                )}

                <div className="grid grid-cols-1 lg:grid-cols-3 gap-8">
                    {/* Participants Column */}
                    <div className="lg:col-span-1 space-y-6">
                        <div className="flex items-center justify-between">
                            <h2 className="text-xl font-semibold flex items-center gap-2">
                                <Users className="w-5 h-5" /> Participants
                            </h2>
                            <span className="text-sm text-neutral-400">{participants.length} total</span>
                        </div>

                        <div className="space-y-4">
                            {participants.map((p) => (
                                <div key={p.id} className="p-4 rounded-xl bg-neutral-900/50 border border-neutral-800 space-y-3">
                                    <div className="flex items-center justify-between">
                                        <span className="font-medium text-white">{p.name}</span>
                                        <span className="text-xs uppercase font-bold text-neutral-500 bg-neutral-950 px-2 py-0.5 rounded border border-neutral-900">{p.role}</span>
                                    </div>

                                    <div className="space-y-1">
                                        <div className="flex justify-between text-xs text-neutral-400">
                                            <span>Talk Time</span>
                                            <span>{formatDuration(p.talk_time_seconds || 0)}</span>
                                        </div>
                                        {/* Simple visualization of talk time contribution (relative to meeting duration approx) */}
                                        <div className="h-1.5 w-full bg-neutral-800 rounded-full overflow-hidden">
                                            <div
                                                className="h-full bg-blue-600 rounded-full"
                                                style={{ width: `${Math.min(100, Math.max(2, ((p.talk_time_seconds || 0) / (totalDurationSeconds || 3600)) * 100))}%` }}
                                            />
                                        </div>
                                    </div>

                                    <div className="pt-2 border-t border-neutral-800/50 flex justify-between text-xs text-neutral-500">
                                        <span>Joined: {new Date(p.joined_at).toLocaleTimeString()}</span>
                                        {p.left_at ? (
                                            <span>Left: {new Date(p.left_at).toLocaleTimeString()}</span>
                                        ) : (
                                            <span className="text-green-500">Active</span>
                                        )}
                                    </div>
                                </div>
                            ))}
                        </div>
                    </div>

                    {/* Transcription Column */}
                    <div className="lg:col-span-2 space-y-6">
                        <div className="flex items-center justify-between">
                            <h2 className="text-xl font-semibold flex items-center gap-2">
                                <FileText className="w-5 h-5" /> Transcript
                            </h2>
                            <Button variant="outline" size="sm" className="h-8 text-xs">Download</Button>
                        </div>

                        <div className="min-h-[500px] max-h-[800px] overflow-y-auto rounded-xl border border-neutral-800 bg-neutral-900/30 p-6 space-y-6">
                            {transcriptions.length === 0 ? (
                                <div className="h-full flex flex-col items-center justify-center text-neutral-500 gap-2 min-h-[200px]">
                                    <FileText className="w-8 h-8 opacity-20" />
                                    <p>No transcription available for this session.</p>
                                </div>
                            ) : (
                                transcriptions.map((t) => (
                                    <div key={t.id} className="flex gap-4">
                                        <div className="shrink-0 w-8 h-8 rounded-full bg-neutral-800 flex items-center justify-center text-xs font-bold text-neutral-400">
                                            {t.speaker_name[0]}
                                        </div>
                                        <div className="space-y-1">
                                            <div className="flex items-baseline gap-2">
                                                <span className="font-semibold text-sm text-neutral-300">{t.speaker_name}</span>
                                                <span className="text-xs text-neutral-600">{new Date(t.timestamp).toLocaleTimeString()}</span>
                                            </div>
                                            <p className="text-neutral-300 leading-relaxed text-sm">
                                                {t.content}
                                            </p>
                                        </div>
                                    </div>
                                ))
                            )}
                        </div>
                    </div>
                </div>
            </div>
        </div >
    )
}
